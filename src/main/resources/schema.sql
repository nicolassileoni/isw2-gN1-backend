DROP TABLE IF EXISTS item_pedido;
DROP TABLE IF EXISTS pedido;
DROP TABLE IF EXISTS producto;
DROP TABLE IF EXISTS categoria;
DROP TABLE IF EXISTS local;
DROP TABLE IF EXISTS repartidor;
DROP TABLE IF EXISTS cliente;
DROP TABLE IF EXISTS usuario;

CREATE TABLE usuario (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(40)  NOT NULL UNIQUE,
    password_hash    VARCHAR(60)  NOT NULL,
    nombre_completo  VARCHAR(100) NOT NULL,
    rol              VARCHAR(20)  NOT NULL CHECK (rol IN ('ADMIN', 'OPERADOR')),
    activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_alta       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categoria (
    id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE local (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(80)  NOT NULL UNIQUE,
    direccion  VARCHAR(120),
    telefono   VARCHAR(15),
    activo     BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE producto (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_id      INT           NOT NULL REFERENCES local(id),
    categoria_id  INT           NOT NULL REFERENCES categoria(id),
    nombre        VARCHAR(80)   NOT NULL,
    descripcion   VARCHAR(200),
    precio        DECIMAL(10,2) NOT NULL CHECK (precio >= 0),
    stock         INT           NOT NULL CHECK (stock >= 0),
    activo        BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE repartidor (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo  VARCHAR(100) NOT NULL,
    telefono         VARCHAR(15),
    activo           BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE cliente (
    id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(80) NOT NULL,
    telefono  VARCHAR(15) NOT NULL UNIQUE
);

CREATE TABLE pedido (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_seguimiento  VARCHAR(8)    NOT NULL UNIQUE,
    cliente_id          INT           NOT NULL REFERENCES cliente(id),
    local_id            INT           NOT NULL REFERENCES local(id),
    repartidor_id       INT           REFERENCES repartidor(id),
    direccion_entrega   VARCHAR(150)  NOT NULL,
    fecha_hora          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado              VARCHAR(20)   NOT NULL DEFAULT 'RECIBIDO'
                        CHECK (estado IN ('RECIBIDO', 'EN_PREPARACION', 'EN_CAMINO', 'ENTREGADO', 'CANCELADO')),
    subtotal            DECIMAL(10,2) NOT NULL,
    descuento           DECIMAL(10,2) NOT NULL,
    costo_envio         DECIMAL(10,2) NOT NULL,
    total               DECIMAL(10,2) NOT NULL
);

CREATE TABLE item_pedido (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        INT           NOT NULL REFERENCES pedido(id),
    producto_id      INT           NOT NULL REFERENCES producto(id),
    cantidad         INT           NOT NULL CHECK (cantidad >= 1),
    precio_unitario  DECIMAL(10,2) NOT NULL,
    CONSTRAINT uq_item_producto UNIQUE (pedido_id, producto_id)
);
